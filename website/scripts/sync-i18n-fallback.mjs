#!/usr/bin/env node
// Fills the ja docs locale with fallback copies of the English docs.
//
// Docusaurus cannot resolve relative .md links in a partially-translated
// locale: a translated page that links `../configuration.md` breaks when
// configuration.md only exists in the English tree, and an English fallback
// page that links to a *translated* page breaks the other way around. The
// standard fix is a full baseline: every English doc that has no real
// translation is copied into the locale tree at build time.
//
// The copies are build artifacts and must never be committed. To keep real
// translations and generated fallbacks distinguishable, this script records
// every file it copies in a manifest (.i18n-fallback-manifest.json) and, on
// the next run, deletes exactly those files before re-syncing. Files not
// listed in the manifest (i.e. real translations) are never deleted or
// overwritten. It also regenerates i18n/.gitignore from the manifest so the
// copies are invisible to git while real translations stay trackable.
//
// Run: node scripts/sync-i18n-fallback.mjs   (from website/)

import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmdirSync,
  unlinkSync,
  copyFileSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const WEBSITE_DIR = path.resolve(__dirname, "..");
const REPO_ROOT = path.resolve(WEBSITE_DIR, "..");
const SOURCE_DIR = path.join(REPO_ROOT, "docs");
const TARGET_DIR = path.join(
  WEBSITE_DIR,
  "i18n",
  "ja",
  "docusaurus-plugin-content-docs",
  "current"
);
const MANIFEST_PATH = path.join(WEBSITE_DIR, ".i18n-fallback-manifest.json");
const I18N_DIR = path.join(WEBSITE_DIR, "i18n");
// Generated ignore file that shields the fallback copies from `git add`
// while leaving real translations visible. This file itself IS committable.
const I18N_GITIGNORE_PATH = path.join(I18N_DIR, ".gitignore");
const I18N_GITIGNORE_HEADER =
  "# Generated by scripts/sync-i18n-fallback.mjs — do not edit; lists build-time English fallback copies";
// Generated ja reference docs (written directly by the schema/openapi
// generators) must never be
// committed, independent of the manifest below.
const I18N_GENERATED_API_IGNORE_LINE =
  "/ja/docusaurus-plugin-content-docs/current/api/";

// Relative-path prefixes (posix-style, matched against SOURCE_DIR-relative
// paths) that must never be copied into the ja locale tree as fallbacks:
// - decisions/: ADRs are excluded from the site entirely.
// - api/: owned directly by the schema/openapi doc generators, which
//   write their own ja pages; a fallback copy here would just be overwritten
//   (or, worse, fight with the generator's rmSync of its own output dir).
const SKIP_PREFIXES = ["decisions/", "api/"];

function isSkipped(relPath) {
  return SKIP_PREFIXES.some((prefix) => relPath === prefix.replace(/\/$/, "") || relPath.startsWith(prefix));
}

/** Convert a relative path to the platform-independent form stored in the manifest. */
function toPosix(relPath) {
  return relPath.split(path.sep).join("/");
}

/** List every file under `dir` as a sorted array of posix-style relative paths. */
function walk(dir, base = dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name)
  )) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walk(full, base));
    } else if (entry.isFile()) {
      files.push(toPosix(path.relative(base, full)));
    }
  }
  return files;
}

/** Remove now-empty directories under `dir` (but never `dir` itself). */
function pruneEmptyDirs(dir, isRoot = true) {
  if (!existsSync(dir)) return;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      pruneEmptyDirs(path.join(dir, entry.name), false);
    }
  }
  if (!isRoot && readdirSync(dir).length === 0) {
    rmdirSync(dir);
  }
}

function loadManifest() {
  if (!existsSync(MANIFEST_PATH)) return [];
  const parsed = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
  if (!Array.isArray(parsed) || parsed.some((p) => typeof p !== "string")) {
    throw new Error(`Malformed manifest at ${MANIFEST_PATH}; expected a JSON array of strings`);
  }
  return parsed;
}

function main() {
  if (!existsSync(SOURCE_DIR)) {
    throw new Error(`English docs directory not found: ${SOURCE_DIR}`);
  }
  mkdirSync(TARGET_DIR, { recursive: true });

  // 1. Delete the fallback copies from the previous run (manifest-listed
  //    files only — anything else in the target tree is a real translation).
  let removed = 0;
  for (const relPath of loadManifest()) {
    // Guard against a tampered manifest reaching outside the target tree.
    const abs = path.resolve(TARGET_DIR, relPath);
    if (!abs.startsWith(TARGET_DIR + path.sep)) continue;
    if (existsSync(abs)) {
      unlinkSync(abs);
      removed++;
    }
  }
  pruneEmptyDirs(TARGET_DIR);

  // 2. Copy every English doc whose relative path is missing in the target
  //    tree. Existing files (real translations) always win.
  const manifest = [];
  let copied = 0;
  for (const relPath of walk(SOURCE_DIR)) {
    if (isSkipped(relPath)) continue;
    const src = path.join(SOURCE_DIR, ...relPath.split("/"));
    const dest = path.join(TARGET_DIR, ...relPath.split("/"));
    if (existsSync(dest)) continue;
    mkdirSync(path.dirname(dest), { recursive: true });
    copyFileSync(src, dest);
    manifest.push(relPath);
    copied++;
  }

  // 3. Record what we copied so the next run can clean up after us.
  manifest.sort();
  writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2) + "\n", "utf8");

  // 4. Regenerate i18n/.gitignore so the fallback copies can never be swept
  //    into a commit of the i18n tree. Fully rewritten from the new manifest
  //    each run, so stale entries disappear automatically; written to a temp
  //    file and renamed so a crash mid-write can't leave a truncated file.
  const targetPrefix = toPosix(path.relative(I18N_DIR, TARGET_DIR));
  const ignoreLines = [I18N_GITIGNORE_HEADER, I18N_GENERATED_API_IGNORE_LINE];
  for (const relPath of manifest) {
    // Anchor each pattern to this .gitignore's directory.
    ignoreLines.push(`/${targetPrefix}/${relPath}`);
  }
  const tmpPath = I18N_GITIGNORE_PATH + ".tmp";
  writeFileSync(tmpPath, ignoreLines.join("\n") + "\n", "utf8");
  renameSync(tmpPath, I18N_GITIGNORE_PATH);

  console.log(
    `i18n fallback sync: removed ${removed} previous cop${removed === 1 ? "y" : "ies"}, ` +
      `copied ${copied} fallback file(s) into ${path.relative(WEBSITE_DIR, TARGET_DIR)}`
  );
}

main();
